    fun search(
        query: String,
        resolveString: (Int) -> String,
    ): List<SettingSearchEntry> {
        val tokens = normalize(query).split(' ').filter(String::isNotBlank)
        if (tokens.isEmpty()) return emptyList()

        return entries.mapNotNull { entry ->
            val title = normalize(resolveString(entry.titleRes))
            val breadcrumb = entry.breadcrumbRes.joinToString(" ") { normalize(resolveString(it)) }
            val aliases = normalize(entry.aliases.joinToString(" "))
            val searchable = "$title $breadcrumb $aliases"
            if (tokens.all(searchable::contains)) {
                val score = when {
                    title == tokens.joinToString(" ") -> 0
                    title.startsWith(tokens.first()) -> 1
                    tokens.all(title::contains) -> 2
                    else -> 3
                }
                score to entry
            } else {
                null
            }
        }.sortedWith(compareBy<Pair<Int, SettingSearchEntry>> { it.first }.thenBy { it.second.id })
            .map { it.second }
    }

    private fun normalize(value: String): String = value
        .lowercase(Locale.ROOT)
        .replace(Regex("[\\s/›>·—–_-]+"), " ")
        .trim()
}
